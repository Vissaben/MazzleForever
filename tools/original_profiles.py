"""Extract presentation data from the original bundled Mazzifier profiles."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.validation/python'))
from lupa.lua51 import LuaRuntime


def original_profile(filename, function):
    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.execute('Mazzifier={}; DUF_Settings={}; Mazzifier_PlayerName="extract"; Mazzifier_ServerName="extract"')
    source = (ROOT / 'Interface/AddOns/Mazzifier/DUF' / filename).read_text(encoding='cp1252')
    lua.execute(source)
    lua.globals().Mazzifier[function](lua.globals().Mazzifier, 'original')
    return lua, lua.globals().DUF_Settings.original, source.split('function ', 1)[0]


def plain(value):
    if hasattr(value, 'items'):
        return {key: plain(item) for key, item in value.items()}
    return value


def literal(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + literal(k) + ']=' + literal(v) for k, v in sorted(value.items(), key=lambda p: str(p[0]))) + '}'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if value is None:
        return 'nil'
    return json.dumps(value, ensure_ascii=True)


def write_styles():
    result = {}
    notice = ''
    for ratio, filename, function in [(1.6, 'DUF_1_6.lua', 'Setup_DUF16'),
                                      (4 / 3, 'DUF_1_33.lua', 'Setup_DUF133'),
                                      (1.25, 'DUF_1_25.lua', 'Setup_DUF125')]:
        lua, data, notice = original_profile(filename, function)
        style = {'aspect': ratio}
        for unit in ('player', 'target', 'pet', 'party'):
            source = data[unit]
            style[unit] = {key: plain(source[key]) for key in ('width', 'height', 'scale', 'xos', 'yos', 'TextBox', 'ClassIcon')}
            style[unit]['bars'] = {index: plain(source.StatusBar[index]) for index in (1, 2)}
        result[ratio] = style
    path = ROOT / 'Interface/AddOns/MazzleUI/Forever/UnitStyles.lua'
    path.write_text(notice + '-- Original presentation data; generated by tools/original_profiles.py.\nlocal _, M = ...\nM.unitStyles = ' + literal(result) + '\n', encoding='utf-8')


if __name__ == '__main__':
    write_styles()
