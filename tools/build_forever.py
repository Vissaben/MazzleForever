"""Package only the original compilation's assets and independent Forever code.

Run with Python 3. No downloaded addon, font, artwork or runtime is incorporated.
The extracted client source and Lua test tools under .validation are test-only.
"""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
import hashlib
import json
import re
import sys
import shutil
from original_profiles import write_styles

ROOT = Path(__file__).resolve().parents[1]
ADDONS = ROOT / "Interface/AddOns"
CORE = ADDONS / "MazzleUI"


def build():
    write_styles()
    font_dir = CORE / 'Forever/Fonts'
    font_dir.mkdir(exist_ok=True)
    for font in ['ARIALN.ttf', 'FRIZQT__.ttf']:
        shutil.copyfile(ROOT / 'Fonts' / font, font_dir / font)
    # Derived from THIS compilation's alpha channels, never another UI's masks.
    sys.path.insert(0, str(ROOT / '.validation/python'))
    from PIL import Image
    texture_dir = CORE / 'Forever/Textures'
    texture_dir.mkdir(exist_ok=True)
    for original, crop_height in [('HL', 256), ('ML', 140)]:
        source_image = Image.open(CORE / 'Art' / (original + '.blp')).convert('RGBA')
        width, height = source_image.size
        alpha = source_image.getchannel('A').crop((0, 0, width, crop_height))
        # The mana image's visible pixels are at its TOP, unlike FauxMazzle PB.
        # Put those pixels at the bottom of a power-of-two mask; the widget clips
        # the transparent top padding without scaling or changing UVs at runtime.
        mask = Image.new('RGBA', (width, height), (255, 255, 255, 0))
        pixels = Image.new('RGBA', (width, crop_height), (255, 255, 255, 255))
        pixels.putalpha(alpha)
        mask.paste(pixels, (0, height - crop_height))
        mask.save(texture_dir / (original + '-left.tga'))
        mask.transpose(Image.Transpose.FLIP_LEFT_RIGHT).save(texture_dir / (original + '-right.tga'))
    skins = [ADDONS / "MazzleUI_Default_Skin"] + sorted(ADDONS.glob("MazzleUI_Skin_*"))
    keys = {"l": "Bottom1.blp", "ml": "Bottom2.blp", "mr": "Bottom3.blp", "r": "Bottom4.blp",
            "cave": "FloatingCave.blp", "mapborder": "MazzleUIMinimapBorder.blp"}
    source = ["-- Original MazzleUI 1.18 skin assets; generated by tools/build_forever.py.",
              "local _, M = ...", "M.skins = {"]
    for skin in skins:
        source.append(f'    ["{skin.name}"] = {{')
        for key, filename in keys.items():
            path = next((p for p in skin.iterdir() if p.name.casefold() == filename.casefold()), None)
            if path is None or not path.is_file():
                raise FileNotFoundError(skin / filename)
            game_path = "Interface\\AddOns\\" + skin.name + "\\" + path.name
            source.append(f'        {key} = {json.dumps(game_path)},')
        source.append("    },")
    source += ["}", "M.skinNames = {" + ", ".join(json.dumps(p.name) for p in skins) + "}", ""]
    (CORE / "Forever/Skins.lua").write_text("\n".join(source), encoding="utf-8")

    # Flavor-specific manifests stop old executables from running when the full
    # historical tree is present. Do not change the original WoW 2.1 manifests.
    for folder in ADDONS.iterdir():
        if not folder.is_dir() or folder == CORE:
            continue
        if folder in skins:
            title, notes = folder.name, "Original MazzleUI artwork. No legacy code is loaded on Forever."
        else:
            title, notes = folder.name + " (legacy, inactive on Forever)", "Legacy module. Use MazzleUI Forever's native replacements."
        content = f"## Interface: 16001\n## Title: {title}\n## Notes: {notes}\n## LoadOnDemand: 1\n"
        (folder / f"{folder.name}_Camelot.toc").write_text(content, encoding="utf-8")

    files = list((CORE / "Forever").glob("*.lua")) + list((CORE / "Art").glob("*"))
    files += list((CORE / "Forever/Textures").glob('*.tga'))
    files += list((CORE / "Forever/Fonts").glob('*.ttf'))
    files += [CORE / "MazzleUI_Camelot.toc"]
    # Retain each original author notice and asset. core.lua is archived for its
    # source provenance, but is NOT listed in any Forever manifest.
    for skin in skins:
        files += list(skin.glob("*.blp")) + [skin / "core.lua", skin / f"{skin.name}_Camelot.toc"]
    archive = ROOT / "MazzleUI-Forever.zip"
    manifest = {}
    with ZipFile(archive, "w", ZIP_DEFLATED) as package:
        for path in sorted(files):
            if not path.is_file():
                continue
            name = path.relative_to(ADDONS).as_posix()
            package.write(path, name)
            manifest[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        # Also provide the base filename for addon managers and clients selecting
        # a plain TOC. It is the SAME modern manifest, never the 2007 loader.
        package.writestr("MazzleUI/MazzleUI.toc", (CORE / "MazzleUI_Camelot.toc").read_bytes())
        package.write(CORE / "Forever/Bindings.xml", "MazzleUI/Bindings.xml")
        for skin in skins:
            package.writestr(f"{skin.name}/{skin.name}.toc", (skin / f"{skin.name}_Camelot.toc").read_bytes())
        package.write(ROOT / "FOREVER-INSTALL.txt", "FOREVER-INSTALL.txt")
        package.writestr("SOURCE-HASHES.json", json.dumps(manifest, indent=2) + "\n")
    print(f"Built {archive.name}: {len(files)} source files, {len(skins)} original skins, {archive.stat().st_size:,} bytes")


if __name__ == "__main__":
    build()
